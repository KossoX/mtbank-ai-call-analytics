def run_ffmpeg(*args: str) -> None:
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", *args], check=True)


async def synthesize(text: str, voice: str, output: Path) -> None:
    communicate = edge_tts.Communicate(text=text, voice=voice)
    await communicate.save(str(output))


async def generate_call(call: CallSpec) -> None:
    name = call["name"]
    sample_rate = call["sample_rate"]
    turns = call["turns"]

    output_audio = CALLS_DIR / f"{name}.wav"
    reference_path = REFERENCES_DIR / f"{name}.txt"
    dialogue_path = REFERENCES_DIR / f"{name}.dialogue.txt"

    with tempfile.TemporaryDirectory(prefix=f"{name}_") as temp_name:
        temp_dir = Path(temp_name)
        wav_parts: list[Path] = []

        for index, (speaker, text) in enumerate(turns):
            voice = OPERATOR_VOICE if speaker == "Оператор" else CLIENT_VOICE
            mp3_path = temp_dir / f"{index:03d}.mp3"
            wav_path = temp_dir / f"{index:03d}.wav"

            await synthesize(text, voice, mp3_path)
            run_ffmpeg(
                "-i",
                str(mp3_path),
                "-ar",
                str(sample_rate),
                "-ac",
                "1",
                "-c:a",
                "pcm_s16le",
                str(wav_path),
            )
            wav_parts.append(wav_path)

            if index != len(turns) - 1:
                silence_path = temp_dir / f"{index:03d}_silence.wav"
                run_ffmpeg(
                    "-f",
                    "lavfi",
                    "-i",
                    f"anullsrc=r={sample_rate}:cl=mono",
                    "-t",
                    str(PAUSE_SECONDS),
                    "-ar",
                    str(sample_rate),
                    "-ac",
                    "1",
                    "-c:a",
                    "pcm_s16le",
                    str(silence_path),
                )
                wav_parts.append(silence_path)

        concat_file = temp_dir / "concat.txt"
        concat_file.write_text(
            "\n".join(f"file '{part}'" for part in wav_parts),
            encoding="utf-8",
        )

        run_ffmpeg(
            "-f",
            "concat",
            "-safe",
            "0",
            "-i",
            str(concat_file),
            "-c",
            "copy",
            str(output_audio),
        )

    plain_reference = " ".join(text for _, text in turns)
    labelled_reference = "\n".join(f"{speaker}: {text}" for speaker, text in turns)

    reference_path.write_text(plain_reference + "\n", encoding="utf-8")
    dialogue_path.write_text(labelled_reference + "\n", encoding="utf-8")

    print(f"created {output_audio} ({sample_rate} Hz)")
    print(f"reference {reference_path}")


async def main() -> None:
    CALLS_DIR.mkdir(parents=True, exist_ok=True)
    REFERENCES_DIR.mkdir(parents=True, exist_ok=True)

    for call in CALLS:
        await generate_call(call)


if __name__ == "__main__":
    asyncio.run(main())
